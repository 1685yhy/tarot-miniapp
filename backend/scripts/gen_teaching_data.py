for suit_key in ["wands","cups","swords","pentacles"]:
    s_zh, s_elem, s_desc = suits[suit_key]
    for rk, r_zh, r_kw, r_story in ranks:
        key = f"{suit_key}_{rk}"
        if key not in CARD_SPEC: continue
        sym_list, life = CARD_SPEC[key]

        # Element description
        if rk in ("page","knight","queen","king"):
            elem_text = f"宫廷牌——{r_zh}是{s_zh}牌组中的{s_elem}元素表达。"
        else:
            elem_text = s_desc

        symbols = [{"symbol": s, "meaning": m} for s, m in sym_list]
        story = f"{s_zh}{r_zh}——{r_story}"

        add(cn, sym_list, story, r_kw, life, elem_text)
        cn += 1

